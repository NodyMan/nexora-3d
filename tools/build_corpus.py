"""Collect the English texts of the classic pages (about, journal, case
studies) into src-v10/corpus.js, so the 3D site uses exactly the same
sentences, and the same Russian / Uzbek translations, as the classic one.
Run from the nexora-3d folder after tools/build_site.py:
    python tools/build_corpus.py
"""
import html
import json
import re

PAGES = ['about', 'journal', 'arise', 'idrok']
seen = []
for page in PAGES:
    s = open(f'site/{page}.html', encoding='utf-8').read()
    s = re.sub(r'<(script|style|header|footer)[\s\S]*?</\1>', '', s)
    # Text nodes as i18n.js sees them: each run of text between tags, trimmed.
    for m in re.finditer(r'>([^<>]+)<', s):
        t = html.unescape(re.sub(r'\s+', ' ', m.group(1))).strip()
        if len(t) > 1 and t not in seen:
            seen.append(t)

with open('src-v10/corpus.js', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/build_corpus.py from the classic pages. Do not edit.\n')
    f.write('export const CORPUS = ' + json.dumps(seen, ensure_ascii=False, indent=0) + ';\n')
print('strings', len(seen))
